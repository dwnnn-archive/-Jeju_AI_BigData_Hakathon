def is_public_holiday(d: date) -> bool:
    return d in HOLIDAYS


def is_day_off(d: date) -> bool:
    """주말 또는 공휴일."""
    return d.weekday() >= 5 or d in HOLIDAYS


def is_covered(d: date) -> bool:
    return FIRST_YEAR <= d.year <= LAST_YEAR


def day_off_context(d: date) -> tuple[int, int]:
    """(전날이 쉬는 날인가, 다음날이 쉬는 날인가). 연휴 첫날·마지막날 효과용."""
    return int(is_day_off(d - timedelta(days=1))), int(is_day_off(d + timedelta(days=1)))
